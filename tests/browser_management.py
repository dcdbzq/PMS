def request(page, origin, method, path, data=None):
    state=page.request.get(origin+'/api/state').json()
    result=page.request.fetch(origin+path,method=method,data=data,headers={'X-CSRF-Token':state['csrf']})
    assert result.ok,result.text()
    return result.json()


def login(page,origin,username,password):
    page.goto(origin)
    page.locator('#auth-username').fill(username)
    page.locator('#auth-password').fill(password)
    page.locator('#auth-form button[type=submit]').click()
    expect(page.locator('.overview-head')).to_be_visible()


